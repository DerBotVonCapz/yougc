// counts change, so these are matched by shape instead of exact text
const RX = [
  [/^(\d+) clips? · (\d+) socials? linked$/i, (m,a,b)=>`${a} clips · ${b} socials verlinkt`],
  [/^(\d+) socials? linked$/i, (m,a)=>`${a} social verlinkt`],
  [/^(\d+) clips? linked$/i, (m,a)=>`${a} clips verlinkt`],
  [/^(\d+) followers?$/i, (m,a)=>`${a} follower`],
  [/^joined (\w+) (\d{4})$/i, (m,a,b)=>`dabei seit ${a} ${b}`],
  [/^(\d+)([hdm]) ago$/i, (m,a,b)=>`vor ${a}${b==='h'?' std':b==='d'?' t':' min'}`],
  [/^just now$/i, ()=>'gerade eben'],
  [/^message (.+?) ?→$/i, (m,a)=>`${a} anschreiben →`],
  [/^message (.+)$/i, (m,a)=>`${a} anschreiben`],
  [/^looking for (\d+) creators? this month,? dm me$/i, (m,a)=>`suche diesen monat ${a} creator, schreib mir`],
];

const KEY = 'yougc_lang';
function pick(){
  try{
    const saved = localStorage.getItem(KEY);
    if(saved) return saved;
    return (navigator.language||'').toLowerCase().startsWith('de') ? 'de' : 'en';
  }catch(e){ return 'en'; }
}
let LANG = pick();
const orig = new WeakMap();

function tr(s){
  const k = s.trim();
  if(!k) return null;
  const g = DE[k];
  if(g) return s.replace(k, g);
  for(const [rx, fn] of RX){
    const m = k.match(rx);
    if(m) return s.replace(k, fn(...m));
  }
  return null;
}
// exposed so scripts can translate a string they build themselves
window.T = (s) => (LANG === 'de' && DE[s]) ? DE[s] : s;

function paint(root){
  if(LANG !== 'de') return;
  const skip = /^(script|style|noscript|textarea)$/i;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: n => (n.parentElement && !skip.test(n.parentElement.tagName) && n.textContent.trim())
      ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT
  });
  const hits = [];
  while(w.nextNode()) hits.push(w.currentNode);
  for(const n of hits){
    const g = tr(n.textContent);
    if(g && g !== n.textContent){ if(!orig.has(n)) orig.set(n, n.textContent); n.textContent = g; }
  }
  if(root.querySelectorAll){
    root.querySelectorAll('[placeholder]').forEach(el=>{
      const g = DE[el.placeholder.trim()];
      if(g) el.placeholder = g;
    });
    root.querySelectorAll('[data-text]').forEach(el=>{
      const g = DE[el.dataset.text.trim()];
      if(g) el.dataset.text = g;
    });
    root.querySelectorAll('[title]').forEach(el=>{
      const g = DE[el.title.trim()];
      if(g) el.title = g;
    });
  }
}

function button(){
  if(document.getElementById('langBtn')) return;
  const b = document.createElement('button');
  b.id = 'langBtn';
  b.type = 'button';
  b.className = 'nav-cta';
  b.title = 'sprache / language';
  b.style.cssText = 'padding:10px 14px;cursor:pointer;font-size:.86rem;line-height:1;font-weight:800;letter-spacing:.03em';
  b.textContent = LANG === 'de' ? 'EN' : 'DE';
  b.addEventListener('click', ()=>{
    LANG = LANG === 'de' ? 'en' : 'de';
    try{ localStorage.setItem(KEY, LANG); }catch(e){}
    location.reload();
  });
  const host = document.querySelector('nav .navlinks') || document.querySelector('nav > div') || document.querySelector('nav');
  if(host) host.appendChild(b);
}

function boot(){
  paint(document.body);
  button();
  // queue every batch. debouncing without a queue silently drops
  // whole renders, which is why some blocks stayed english.
  let t = null;
  const queue = new Set();
  const flush = () => {
    t = null;
    const nodes = [...queue]; queue.clear();
    for(const n of nodes){
      if(!n.isConnected) continue;
      if(n.nodeType === 1) paint(n);
      else if(n.nodeType === 3){ const g = tr(n.textContent); if(g) n.textContent = g; }
    }
    button();
  };
  new MutationObserver(muts=>{
    if(LANG !== 'de') return;
    for(const m of muts){
      for(const n of m.addedNodes) queue.add(n);
      if(m.type === 'characterData') queue.add(m.target);
    }
    if(!t) t = setTimeout(flush, 50);
  }).observe(document.body, { childList:true, subtree:true, characterData:true });
}

if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
else boot();

